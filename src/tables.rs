/// Block component class (selects the DC Huffman table in BS v3).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Component {
    /// Luminance (Y).
    Luma,
    /// Chrominance (Cr or Cb).
    Chroma,
}

/// Returns the BS v3 DC-difference Huffman table for `component`.
#[inline]
pub const fn dc_table(component: Component) -> &'static [DcCode; 9] {
    match component {
        Component::Luma => &DC_LUMA,
        Component::Chroma => &DC_CHROMA,
    }
}

