#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn zigzag_is_valid_permutation() {
        let mut seen = [false; 64];
        for &idx in &ZIGZAG {
            assert!(!seen[idx]);
            seen[idx] = true;
        }
        assert!(seen.iter().all(|&b| b));
    }

    #[test]
    fn default_quant_matches_zigzag_of_natural() {
        assert_eq!(
            quant_natural_to_zigzag(&QUANT_MATRIX_NATURAL),
            DEFAULT_QUANT_LUMA
        );
        assert_eq!(
            quant_zigzag_to_natural(&DEFAULT_QUANT_LUMA),
            QUANT_MATRIX_NATURAL
        );
    }
}
